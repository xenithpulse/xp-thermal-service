#!/usr/bin/env node
/**
 * Builds public/dashboard.html from src/dashboard/:
 *
 *   dashboard.html   markup and script, styled with Tailwind classes
 *   dashboard.css    the Tailwind entry point: theme tokens and components
 *
 * Tailwind compiles only the classes the page uses, and the result is inlined
 * into one self-contained file. That file is what the service serves, what the
 * exe embeds as an SEA asset, and what a POS install copies: none of them can
 * rely on a CDN, because tills are often offline.
 *
 * public/dashboard.html is committed, so running from source works without a
 * build step; edit src/dashboard/ and rebuild rather than editing it.
 *
 *   node scripts/build-dashboard.mjs           write public/dashboard.html
 *   node scripts/build-dashboard.mjs --check   exit 1 if it is out of date
 *   node scripts/build-dashboard.mjs --watch   rebuild on every change
 */

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const at = (...p) => path.join(root, ...p);

const SOURCE_HTML = at('src', 'dashboard', 'dashboard.html');
const SOURCE_CSS = at('src', 'dashboard', 'dashboard.css');
const OUTPUT = at('public', 'dashboard.html');
const MARKER = '<style>/* tailwind */</style>';
const BANNER = '<!-- Generated by scripts/build-dashboard.mjs from src/dashboard/. Edit those files, then run: npm run build:dashboard -->';
// Tailwind colours its errors; the escape codes are stripped so they read in a log.
const ANSI = new RegExp(`${String.fromCharCode(27)}\\[[0-9;]*m`, 'g');

function compileCss() {
  const cli = at('node_modules', '@tailwindcss', 'cli', 'dist', 'index.mjs');
  if (!fs.existsSync(cli)) throw new Error('Tailwind is not installed. Run npm install.');
  const tmp = at('build', 'dashboard.css');
  fs.mkdirSync(path.dirname(tmp), { recursive: true });
  try {
    execFileSync(process.execPath, [cli, '-i', SOURCE_CSS, '-o', tmp, '--minify'], { cwd: root, stdio: ['ignore', 'ignore', 'pipe'] });
  } catch (error) {
    const detail = String(error.stderr ?? '').replace(ANSI, '').trim();
    throw new Error(`Tailwind could not compile ${path.relative(root, SOURCE_CSS)}:\n${detail}`);
  }
  const css = fs.readFileSync(tmp, 'utf8').trim();
  fs.rmSync(tmp, { force: true });
  return css;
}

function render() {
  const html = fs.readFileSync(SOURCE_HTML, 'utf8').replace(/\r\n/g, '\n');
  if (!html.includes(MARKER)) throw new Error(`${path.relative(root, SOURCE_HTML)} has no ${MARKER} placeholder.`);
  // A function replacement, so "$&" and friends in the CSS are left alone.
  return html
    .replace(MARKER, () => `<style>${compileCss()}</style>`)
    .replace(/^<!DOCTYPE html>\n/i, (doctype) => `${doctype}${BANNER}\n`);
}

function build() {
  const started = Date.now();
  const out = render();
  fs.writeFileSync(OUTPUT, out, 'utf8');
  console.log(`Wrote ${path.relative(root, OUTPUT)} (${(out.length / 1024).toFixed(0)} KB) in ${Date.now() - started} ms`);
}

if (process.argv.includes('--check')) {
  // Line endings are normalised: git may check the file out with CRLF.
  const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== render()) {
    console.error('public/dashboard.html is out of date with src/dashboard/. Run: npm run build:dashboard');
    process.exit(1);
  }
  console.log('public/dashboard.html is up to date.');
} else {
  build();
  if (process.argv.includes('--watch')) {
    let timer = null;
    console.log('Watching src/dashboard/ …');
    fs.watch(at('src', 'dashboard'), () => {
      clearTimeout(timer);
      timer = setTimeout(() => {
        try {
          build();
        } catch (error) {
          console.error(error.message);
        }
      }, 120);
    });
  }
}
